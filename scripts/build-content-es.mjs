// Builds src/game/i18n/content-es.js (English → Spanish lookup) from translations/content.tsv.
import { readFileSync, writeFileSync } from "node:fs";
const rows = readFileSync(new URL("../translations/content.tsv", import.meta.url), "utf8").split("\n").filter(Boolean).map((l) => l.split("\t"));
const obj = {};
for (const [en, es] of rows) {
  if (en in obj && obj[en] !== es) throw new Error(`Conflicting translations for: ${en}`);
  obj[en] = es;
}
const out = `// GENERATED by scripts/build-content-es.mjs from translations/content.tsv — do not edit by hand.\nexport const CONTENT_ES = ${JSON.stringify(obj, null, 0).replace(/","/g, '",\n"')};\n`;
writeFileSync(new URL("../src/game/i18n/content-es.js", import.meta.url), out);
console.log(`${Object.keys(obj).length} entries`);

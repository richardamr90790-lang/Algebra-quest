// Builds src/game/i18n/steps-es.js (English step pattern -> Spanish pattern) from translations/steps.tsv.
import { readFileSync, writeFileSync } from "node:fs";
const rows = readFileSync(new URL("../translations/steps.tsv", import.meta.url), "utf8").split("\n").filter(Boolean).map((l) => l.split("\t"));
const obj = {};
for (const [en, es] of rows) {
  if (es === undefined) throw new Error(`No Spanish for: ${en}`);
  const a = (en.match(/\{\d+\}/g) || []).sort().join(), b = (es.match(/\{\d+\}/g) || []).sort().join();
  if (a !== b) throw new Error(`Placeholders differ: ${en}  /  ${es}`);
  if (en in obj && obj[en] !== es) throw new Error(`Conflicting translations for: ${en}`);
  obj[en] = es;
}
writeFileSync(new URL("../src/game/i18n/steps-es.js", import.meta.url), `// GENERATED by scripts/build-steps-es.mjs from translations/steps.tsv — do not edit by hand.\nexport const STEPS_ES = ${JSON.stringify(obj).replace(/","/g, '",\n"')};\n`);
console.log(`${Object.keys(obj).length} step patterns`);
